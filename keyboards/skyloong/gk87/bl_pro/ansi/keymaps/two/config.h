#pragma once

// ── 一次性符号层（点按 F 进入的 _SYM）的超时 ─────────────────────────────────
//
// QMK 核心默认**不设超时**（只有定义了 ONESHOT_TIMEOUT 才启用），也就是说点一下 F
// 之后符号层会一直挂着，直到你敲下一个键。给个上限更安全：误点 F 也能自己恢复。
// 想要「永不超时」把下面这行删掉即可。
#define ONESHOT_TIMEOUT 5000

// ── 让两个分裂空格的修饰键立即生效 ───────────────────────────────────────────
//
// 两个分裂空格是 tap-hold（按住 = Ctrl / Shift，点按 = 切层）。默认情况下 MT 要等
// TAPPING_TERM（200ms）才知道是按住，于是「按住左空格马上按 C」会被判成点按、
// 出来的是普通的 c 而不是 Ctrl+C。它们的主用途恰恰就是 Ctrl+C / Ctrl+V 和
// Shift+字母，必须瞬时，所以打开 per-key 版本。
//
// 效果：按住期间只要按下了别的键，立刻当「按住」处理。
// 代价：想进 ctrl / shift 层就得**先松开**空格（这正是设计里写的「快按」）。
// 只对这两个键生效，实现在 keymap.c 的 get_hold_on_other_key_press()。
//
// ⚠ F（一次性符号层）用的是 OSL，**不是 tap-hold**，所以不受 TAPPING_TERM 影响、
//   也不在这个名单里 —— 按下即生效，没有延迟。
#define HOLD_ON_OTHER_KEY_PRESS_PER_KEY

// ── 下面这些都用 QMK 默认值，需要时再打开 ───────────────────────────────────
//
// 1) tap/hold 的判定时间（分裂空格、Esc/Caps、Tab 靠它区分点按/按住），默认 200ms：
//
//        #define TAPPING_TERM 200
//
// 2) ⚠ 不要 打开 ONESHOT_TAP_TOGGLE。
//    它会把「连点两下 F」变成「锁定/解锁符号层」，但本设计里连点两下 F 是要
//    **输出 `/`** 的（`_SYM[3,4]` = KC_SLSH，也就是 KLE 上 F 位键帽左下写的那个 `/`）。
//    这是有意为之：符号层的每一个符号都靠「F + 那个键」得到，`/` 自然就是「F + F」。
//    开了 TAP_TOGGLE 就等于把 `/` 吃掉，而且还会因为 2 次点击的间隔产生歧义。
//
//    当前（不开）的时序：
//      F 第 1 下 -> 进入符号层
//      F 第 2 下 -> 在符号层解析 -> 输出 `/`，同时符号层被消费、自动关
//
// 3) 要连打多个符号（如 `(){}[]`）：每个符号前点一下 F 即可。
//    不要去开 ONESHOT_TAP_TOGGLE（见上）。
